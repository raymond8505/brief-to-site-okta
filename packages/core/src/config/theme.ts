import { hexToHsl, hexToRgb, type HSL, type RGB } from "../styles/palette";
import { DEFAULT_RADIUS, RADIUS_PRESETS } from "../styles/radius";
import type { BrandConfig } from "./brand.schema";

/**
 * `buildThemeCss` — the core of `theme:build`. Turns a validated `brand.json` into the
 * per-site `theme.css` that overrides core's brand seeds (imported after globals.css). Pure and
 * fs-free so it is unit-testable and reusable by `sites:new` (which writes the initial theme).
 *
 * What it emits, and why (see styles/colors.css for the consuming derivation):
 * - `--brand-h/s/l` from the primary hex — the seed the whole palette derives from.
 * - `--brand-r/g/b` from the primary hex — the RGB the pure-CSS `.wcag-contrast` utility reads to
 *   pick a legible text colour. theme:build does ONLY hex→RGB here (no luminance/contrast math):
 *   contrast is a CSS + component concern.
 * - `--secondary-h-offset` / `--tertiary-h-offset` pointed at the chosen harmony's named vars, so
 *   colors.css derives secondary/tertiary via its `calc(var(--brand-h) + …)` rules. Derived colours
 *   are intentionally NOT written out — the CSS owns that math.
 * - `--brand-secondary-*` / `--brand-tertiary-*` (HSL + RGB) ONLY when brand.json supplies an
 *   explicit hex, overriding the harmony derivation for that colour.
 * - `--radius` ONLY when the chosen radius preset differs from the default — it rescales every
 *   `rounded-*` corner in the site (see styles/radius.ts). The default preset emits nothing, so a
 *   default-brand `theme.css` stays byte-identical to before radius existed.
 */

const GENERATED_HEADER = `/* GENERATED by \`theme:build\` — do not edit.
   Edit config/brand.json and re-run \`yarn theme:build <site>\`. */`;

/** The HSL channel declarations for a brand token at `--<prefix>-h/s/l`. */
function hslBlock(prefix: string, { h, s, l }: HSL): string {
  return [`  --${prefix}-h: ${h};`, `  --${prefix}-s: ${s};`, `  --${prefix}-l: ${l};`].join("\n");
}

/** The RGB channel declarations for a brand token at `--<prefix>-r/g/b` (for `.wcag-contrast`). */
function rgbBlock(prefix: string, { r, g, b }: RGB): string {
  return [`  --${prefix}-r: ${r};`, `  --${prefix}-g: ${g};`, `  --${prefix}-b: ${b};`].join("\n");
}

/** HSL + RGB channels for one brand colour from its hex. */
function colorBlock(prefix: string, hex: string): string {
  return `${hslBlock(prefix, hexToHsl(hex))}\n${rgbBlock(prefix, hexToRgb(hex))}`;
}

export function buildThemeCss(brand: BrandConfig): string {
  const lines: string[] = [GENERATED_HEADER, "", ":root {"];

  lines.push("  /* Brand seed — brand.json `primary` (hex → HSL for the palette + RGB for .wcag-contrast). */");
  lines.push(colorBlock("brand", brand.primary));

  lines.push("");
  lines.push(`  /* Colour harmony (${brand.harmony}) — colors.css derives secondary/tertiary. */`);
  lines.push(`  --secondary-h-offset: var(--secondary-h--${brand.harmony});`);
  lines.push(`  --tertiary-h-offset: var(--tertiary-h--${brand.harmony});`);

  if (brand.secondary) {
    lines.push("");
    lines.push("  /* Explicit secondary brand colour (overrides the harmony derivation). */");
    lines.push(colorBlock("brand-secondary", brand.secondary));
  }
  if (brand.tertiary) {
    lines.push("");
    lines.push("  /* Explicit tertiary brand colour (overrides the harmony derivation). */");
    lines.push(colorBlock("brand-tertiary", brand.tertiary));
  }

  if (brand.radius !== DEFAULT_RADIUS) {
    lines.push("");
    lines.push(`  /* Corner-radius style signal (${brand.radius}) — rescales every rounded-* corner. */`);
    lines.push(`  --radius: ${RADIUS_PRESETS[brand.radius]};`);
  }

  lines.push("}", "");
  return lines.join("\n");
}
