import { describe, expect, it } from "vitest";

import type { BrandConfig } from "./brand.schema";
import { buildThemeCss } from "./theme";

// #7c3aed is Tailwind violet-600 → hsl(262 83% 58%); asserted against palette.hexToHsl elsewhere.
const violet: BrandConfig = { primary: "#7c3aed", harmony: "complementary" };

describe("buildThemeCss", () => {
  it("emits the primary seed as integer HSL channels", () => {
    const css = buildThemeCss(violet);
    expect(css).toContain("--brand-h: 262;");
    expect(css).toContain("--brand-s: 83;");
    expect(css).toContain("--brand-l: 58;");
  });

  it("points the harmony offsets at the chosen harmony's named vars", () => {
    expect(buildThemeCss(violet)).toContain("--secondary-h-offset: var(--secondary-h--complementary);");
    expect(buildThemeCss({ primary: "#7c3aed", harmony: "triadic" })).toContain(
      "--tertiary-h-offset: var(--tertiary-h--triadic);",
    );
  });

  it("precomputes an auto-legible --primary-foreground", () => {
    // Violet-600 is dark enough to take white text.
    expect(buildThemeCss(violet)).toContain("--primary-foreground: #ffffff;");
    // A bright yellow primary must flip to black text.
    expect(buildThemeCss({ primary: "#facc15", harmony: "complementary" })).toContain(
      "--primary-foreground: #000000;",
    );
  });

  it("omits derived secondary/tertiary channels but writes explicit ones", () => {
    const derived = buildThemeCss(violet);
    expect(derived).not.toContain("--brand-secondary-h:");
    expect(derived).not.toContain("--brand-tertiary-h:");

    const explicit = buildThemeCss({
      primary: "#7c3aed",
      secondary: "#22d3ee",
      tertiary: "#f97316",
      harmony: "complementary",
    });
    expect(explicit).toContain("--brand-secondary-h:");
    expect(explicit).toContain("--brand-tertiary-h:");
  });

  it("prepends a GENERATED header and opens a :root block", () => {
    const css = buildThemeCss(violet);
    expect(css.startsWith("/* GENERATED by `theme:build`")).toBe(true);
    expect(css).toContain(":root {");
    expect(css.trimEnd().endsWith("}")).toBe(true);
  });
});
